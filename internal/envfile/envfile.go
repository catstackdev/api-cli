// Package envfile reads .env files for their KEY NAMES, to generate and check a
// .env.example. It never loads values into the process: .env files are
// sourced by the shell (so $VAR expansion keeps its zsh semantics), and values
// only leave this package on request, with secret-looking ones always blanked.
package envfile

import (
	"bytes"
	"regexp"
	"sort"
	"strings"

	"cybercat/api/internal/secret"
)

// Entry is one KEY=value line plus the comment lines directly above it.
type Entry struct {
	Key      string
	Value    string
	Comments []string
}

var (
	keyLine = regexp.MustCompile(`^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$`)

	// scheme://user:password@host
	urlCreds = regexp.MustCompile(`://[^/\s:@]+:[^@\s/]+@`)
)

// IsSecretKey reports whether a key name looks like it holds a secret.
func IsSecretKey(key string) bool { return secret.Name(key) }

// HasCredentials reports whether a value embeds credentials (user:pass@host).
func HasCredentials(value string) bool { return urlCreds.MatchString(value) }

// Parse extracts entries in file order. Blank lines reset the pending comment
// block, so a comment only sticks to the key right below it.
func Parse(data []byte) []Entry {
	var out []Entry
	var comments []string
	for _, raw := range strings.Split(strings.ReplaceAll(string(data), "\r\n", "\n"), "\n") {
		line := strings.TrimRight(raw, " \t")
		switch {
		case strings.TrimSpace(line) == "":
			comments = nil
		case strings.HasPrefix(strings.TrimSpace(line), "#"):
			comments = append(comments, strings.TrimSpace(line))
		default:
			if m := keyLine.FindStringSubmatch(line); m != nil {
				out = append(out, Entry{Key: m[1], Value: unquoteValue(m[2]), Comments: comments})
			}
			comments = nil
		}
	}
	return out
}

// unquoteValue returns the value without surrounding quotes or a trailing
// " # comment" (only the first word of intent: it is for display, not loading).
func unquoteValue(s string) string {
	s = strings.TrimSpace(s)
	if len(s) >= 2 && (s[0] == '"' || s[0] == '\'') {
		if end := strings.IndexByte(s[1:], s[0]); end >= 0 {
			return s[1 : 1+end]
		}
	}
	if i := strings.Index(s, " #"); i >= 0 {
		s = s[:i]
	}
	return strings.TrimSpace(s)
}

// Source is a parsed file.
type Source struct {
	Name    string // e.g. ".env.staging"
	Entries []Entry
}

// Keys returns the key names of a source, in order.
func (s Source) Keys() []string {
	keys := make([]string, len(s.Entries))
	for i, e := range s.Entries {
		keys[i] = e.Key
	}
	return keys
}

// Example renders a .env.example from the union of keys across sources (first
// seen order). Values are blank unless keepValues, and a secret-looking key or a
// value with embedded credentials is blank even then. A key's value and
// comments come from the first source that has them.
func Example(sources []Source, keepValues bool) string {
	var order []string
	first := map[string]Entry{}
	for _, src := range sources {
		for _, e := range src.Entries {
			if cur, ok := first[e.Key]; !ok {
				order = append(order, e.Key)
				first[e.Key] = e
			} else {
				if cur.Value == "" && e.Value != "" {
					cur.Value = e.Value
				}
				if len(cur.Comments) == 0 {
					cur.Comments = e.Comments
				}
				first[e.Key] = cur
			}
		}
	}

	var b bytes.Buffer
	b.WriteString("# Generated by `api env example`: keys only, no secrets.\n")
	b.WriteString("# Copy to .env.<name> and fill in the values.\n\n")
	for _, k := range order {
		e := first[k]
		for _, c := range e.Comments {
			b.WriteString(c + "\n")
		}
		val := ""
		if keepValues && !IsSecretKey(k) && !HasCredentials(e.Value) {
			val = e.Value
		}
		b.WriteString(k + "=" + val + "\n")
	}
	return b.String()
}

// Drift is the difference between one file and the example.
type Drift struct {
	File    string
	Missing []string // in the example, not in the file
	Extra   []string // in the file, not in the example (undocumented)
}

// Check compares each source with the example's keys.
func Check(example []string, sources []Source) []Drift {
	want := map[string]bool{}
	for _, k := range example {
		want[k] = true
	}
	var out []Drift
	for _, src := range sources {
		have := map[string]bool{}
		for _, k := range src.Keys() {
			have[k] = true
		}
		d := Drift{File: src.Name}
		for _, k := range example {
			if !have[k] {
				d.Missing = append(d.Missing, k)
			}
		}
		for _, k := range src.Keys() {
			if !want[k] {
				d.Extra = append(d.Extra, k)
			}
		}
		sort.Strings(d.Missing)
		sort.Strings(d.Extra)
		if len(d.Missing) > 0 || len(d.Extra) > 0 {
			out = append(out, d)
		}
	}
	return out
}
